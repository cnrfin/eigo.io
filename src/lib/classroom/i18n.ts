export type ClassroomT = (key: Keys, vars?: Record<string, string | number>) => string

export function makeT(lang: ClassroomLang): ClassroomT {
  const dict = lang === 'ja' ? ja : en
  return (key, vars) => {
    let s = dict[key] ?? en[key]
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}
